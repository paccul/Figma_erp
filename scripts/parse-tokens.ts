import * as fs from 'fs';
import * as path from 'path';

interface ColorValue {
  light: string;
  dark: string;
}

interface TokenItem {
  type: string;
  value: ColorValue | string;
  description?: string;
}

interface TokensData {
  name?: string;
  modes?: Record<string, string>;
  tokens?: Record<string, any>;
  [key: string]: any;
}

interface ParsedTokenResult {
  colorTokens: Array<{ name: string; light: string; dark: string; description?: string }>;
  fontTokens: Array<{ name: string; value: string }>;
  radiusTokens: Array<{ name: string; value: string }>;
}

const TOKENS_FILE = path.resolve(process.cwd(), 'tokens.json');
const GLOBALS_CSS_FILE = path.resolve(process.cwd(), 'src/app/globals.css');

const MARKER_START = '/* ==========================================================================\n   FIGMA DESIGN TOKENS (GENERATED BY scripts/parse-tokens.ts - DO NOT EDIT)\n   Source: tokens.json\n   ========================================================================== */';
const MARKER_END = '/* ==========================================================================\n   END FIGMA DESIGN TOKENS\n   ========================================================================== */';

function normalizeTokenName(pathParts: string[]): string {
  return pathParts
    .join('-')
    .toLowerCase()
    .replace(/[^a-z0-9_-]/g, '-');
}

function parseTokensJson(data: TokensData): ParsedTokenResult {
  const result: ParsedTokenResult = {
    colorTokens: [],
    fontTokens: [],
    radiusTokens: []
  };

  const rootTokens = data.tokens || data;

  function traverse(node: any, currentPath: string[] = []): void {
    if (!node || typeof node !== 'object') return;

    // Check if this node is a leaf token item (has 'type' and 'value')
    if ('type' in node && 'value' in node) {
      const token = node as TokenItem;
      const tokenType = String(token.type).toLowerCase();

      if (tokenType === 'color') {
        const name = normalizeTokenName(currentPath);
        if (typeof token.value === 'object' && token.value !== null) {
          const valObj = token.value as any;
          const light = valObj.light || valObj['Light'] || valObj.default || '#000000';
          const dark = valObj.dark || valObj['Dark'] || valObj['Dark (Default)'] || valObj.default || '#000000';
          result.colorTokens.push({
            name,
            light,
            dark,
            description: token.description
          });
        } else if (typeof token.value === 'string') {
          result.colorTokens.push({
            name,
            light: token.value,
            dark: token.value,
            description: token.description
          });
        }
      } else if (tokenType === 'fontfamilies' || tokenType === 'fontfamily' || tokenType === 'font') {
        const cleanParts = currentPath.filter(p => !p.toLowerCase().includes('font'));
        const name = normalizeTokenName(cleanParts.length > 0 ? cleanParts : currentPath);
        result.fontTokens.push({
          name,
          value: String(token.value)
        });
      } else if (tokenType === 'borderradius' || tokenType === 'radius') {
        const cleanParts = currentPath.filter(p => !p.toLowerCase().includes('radius'));
        const name = normalizeTokenName(cleanParts.length > 0 ? cleanParts : currentPath);
        result.radiusTokens.push({
          name,
          value: String(token.value)
        });
      }
      return;
    }

    // Traverse children
    for (const [key, child] of Object.entries(node)) {
      if (key.startsWith('$')) continue; // Skip schema and metadata
      traverse(child, [...currentPath, key]);
    }
  }

  traverse(rootTokens);
  return result;
}

function generateCssBlock(parsed: ParsedTokenResult): string {
  const themeLines: string[] = [];
  const rootLines: string[] = [];
  const darkLines: string[] = [];

  // 1. Color Custom Properties
  for (const color of parsed.colorTokens) {
    const varName = `--color-${color.name}`;
    themeLines.push(`  ${varName}: var(${varName});`);
    rootLines.push(`  ${varName}: ${color.light};`);
    darkLines.push(`  ${varName}: ${color.dark};`);
  }

  // 2. Font Families
  if (parsed.fontTokens.length > 0) {
    themeLines.push('');
    themeLines.push('  /* Font Families */');
    for (const font of parsed.fontTokens) {
      themeLines.push(`  --font-${font.name}: ${font.value};`);
    }
  }

  // 3. Border Radii
  if (parsed.radiusTokens.length > 0) {
    themeLines.push('');
    themeLines.push('  /* Border Radii */');
    for (const r of parsed.radiusTokens) {
      themeLines.push(`  --radius-${r.name}: ${r.value};`);
    }
  }

  return `${MARKER_START}
@theme {
${themeLines.join('\n')}
}

:root {
${rootLines.join('\n')}
}

.dark {
${darkLines.join('\n')}
}
${MARKER_END}`;
}

export function syncTokens(): void {
  console.log(`[sync:tokens] Membaca tokens dari: ${TOKENS_FILE}`);

  if (!fs.existsSync(TOKENS_FILE)) {
    throw new Error(`File tokens.json tidak ditemukan di: ${TOKENS_FILE}`);
  }

  let rawContent: string;
  try {
    rawContent = fs.readFileSync(TOKENS_FILE, 'utf8');
  } catch (err: any) {
    throw new Error(`Gagal membaca file tokens.json: ${err.message}`);
  }

  let data: TokensData;
  try {
    data = JSON.parse(rawContent);
  } catch (err: any) {
    throw new Error(`Format tokens.json tidak valid (JSON Parse Error): ${err.message}`);
  }

  const parsed = parseTokensJson(data);

  if (parsed.colorTokens.length === 0) {
    throw new Error('Tidak ditemukan token warna (type: "color") di dalam tokens.json!');
  }

  console.log(`[sync:tokens] Ditemukan ${parsed.colorTokens.length} warna (Light & Dark), ${parsed.fontTokens.length} font, ${parsed.radiusTokens.length} radius.`);

  const generatedBlock = generateCssBlock(parsed);

  const dir = path.dirname(GLOBALS_CSS_FILE);
  if (!fs.existsSync(dir)) {
    fs.mkdirSync(dir, { recursive: true });
    console.log(`[sync:tokens] Membuat direktori: ${dir}`);
  }

  let existingContent = '';
  if (fs.existsSync(GLOBALS_CSS_FILE)) {
    existingContent = fs.readFileSync(GLOBALS_CSS_FILE, 'utf8');
  } else {
    existingContent = `@import "tailwindcss";\n\nbody {\n  background-color: var(--color-bg-canvas);\n  color: var(--color-text-primary);\n  font-family: var(--font-ui, sans-serif);\n}\n`;
  }

  let newContent = '';
  const startIndex = existingContent.indexOf(MARKER_START);
  const endIndex = existingContent.indexOf(MARKER_END);

  if (startIndex !== -1 && endIndex !== -1 && endIndex > startIndex) {
    // Timpa HANYA bagian token di antara marker (preserve seluruh kode lain)
    const before = existingContent.substring(0, startIndex);
    const after = existingContent.substring(endIndex + MARKER_END.length);
    newContent = before + generatedBlock + after;
    console.log(`[sync:tokens] Berhasil memperbarui blok token khusus di globals.css (kode lain tetap utuh).`);
  } else {
    // Jika belum ada marker, selipkan setelah @import "tailwindcss"; atau di awal
    if (existingContent.includes('@import "tailwindcss";')) {
      newContent = existingContent.replace(
        '@import "tailwindcss";',
        `@import "tailwindcss";\n\n${generatedBlock}`
      );
    } else {
      newContent = `${generatedBlock}\n\n${existingContent}`;
    }
    console.log(`[sync:tokens] Menyisipkan blok token baru ke dalam globals.css.`);
  }

  fs.writeFileSync(GLOBALS_CSS_FILE, newContent, 'utf8');
  console.log(`[sync:tokens] BERHASIL! File ${GLOBALS_CSS_FILE} telah disinkronkan dengan tema Tailwind v4.`);
}

// Jalankan jika dipanggil via CLI
if (require.main === module || process.argv[1]?.endsWith('parse-tokens.ts')) {
  try {
    syncTokens();
  } catch (err: any) {
    console.error(`[sync:tokens] ERROR: ${err.message}`);
    process.exit(1);
  }
}
